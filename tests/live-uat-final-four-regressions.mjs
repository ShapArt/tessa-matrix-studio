import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tms-live-final-four-'));
const target = path.join(tmp, 'tessa-matrix-studio.user.js');
fs.copyFileSync(path.join(root, 'tessa-matrix-studio.user.js'), target);

const run = args => {
  const result = spawnSync(process.execPath, args, { cwd: root, encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`Command failed: node ${args.join(' ')}\n${result.stdout || ''}\n${result.stderr || ''}`);
};

try {
  run(['hotfixes/malformed-range-diagnostic-transform.mjs', target]);
  run(['hotfixes/v1.13.0-user-row-lifecycle-transform.mjs', target]);
  fs.appendFileSync(target, `\n${fs.readFileSync(path.join(root, 'hotfixes/interval-add-valid-fallback.js'), 'utf8')}\n`);
  run(['hotfixes/v1.13.0-full-uat-live-finalize.mjs', target]);
  run(['hotfixes/v1.14-full-uat-inline-failures.mjs', target]);
  const finalFourTransform = path.join(root, 'hotfixes/v1.14-live-uat-final-four.mjs');
  if (fs.existsSync(finalFourTransform)) run(['hotfixes/v1.14-live-uat-final-four.mjs', target]);
  run(['--check', target]);

  const source = fs.readFileSync(target, 'utf8');

  // Seed 874674273: production picker has data (23 catalogs / 133763 entries), but Full UAT
  // called pickerColumns with the wrong two-argument shape. The UAT must use the same
  // production source contract as the real picker UI.
  assert.match(source, /FULL_UAT_PICKER_SOURCE_V2/,
    'composed Full UAT must mark the production-shaped picker source');
  assert.doesNotMatch(source, /E\.pickerColumns\(structure, catalog\)/,
    'Full UAT must not call pickerColumns with the obsolete two-argument shape');

  // Seed 4056656365: after schemaTokens + dictionaryCatalog were fixed, both
  // action-value-picker and dictionary-audit still crashed at source.headers[index].
  // The Full UAT source must therefore carry all three production picker inputs.
  assert.match(source, /E\.pickerColumns\(\{\s*schemaTokens:\s*base\.book\.schemaTokens,\s*headers:\s*base\.book\.headers,\s*dictionaryCatalog:\s*catalog\s*\}\)/,
    'Full UAT picker checks must pass schema tokens, matching headers and the live catalog');

  // Seed 874674273: dictionary refresh generated a >128 MiB service worksheet and then
  // incorrectly fed its own trusted donor ZIP back through the untrusted XLSX reader.
  // Keep the 128 MiB guard for external files, but build the replacement dictionary XML
  // directly from the already-normalized live catalog without donor ZIP inflate.
  assert.match(source, /MaxEntryUncompressedBytes:\s*128\s*\*\s*1024\s*\*\s*1024/,
    'external XLSX per-entry guard must stay at 128 MiB');
  assert.match(source, /REFRESH_DICTIONARY_DIRECT_XML_V2/,
    'dictionary refresh must use direct generated XML instead of a donor unzip roundtrip');
  assert.doesNotMatch(source, /const donorBytes = await createRoundtripXlsxBytes\(structure, \{ rows: \[\] \}, \{\}, catalog\);[\s\S]{0,500}await unzipArrayBuffer\(donorBytes/,
    'dictionary refresh must never inflate its own generated donor workbook');

  // Seed 874674273: Boolean writes read back as true/false while the workbook-facing
  // candidate is Да/Нет. Compare Boolean semantics, not localized display text.
  assert.match(source, /FULL_UAT_BOOLEAN_SEMANTIC_V2/,
    'Full UAT field read-back must normalize Boolean display values to server semantics');
  assert.match(source, /\['да', 'true', '1'\]\.includes\(value\) \? 'true'/,
    'Boolean true aliases must normalize to true');
  assert.match(source, /\['нет', 'false', '0'\]\.includes\(value\) \? 'false'/,
    'Boolean false aliases must normalize to false');

  // Cheap behavioral reproduction of the refresh bug: the source workbook is tiny and
  // retained normally; only the fresh replacement catalog crosses the synthetic 64 KiB
  // service-sheet ceiling. Refresh must succeed because that XML is generated by us, not
  // parsed from an untrusted user archive.
  globalThis.window = globalThis;
  globalThis.__TESSA_MATRIX_SYNC_TEST_MODE__ = true;
  globalThis.__TESSA_MATRIX_SYNC_TEST_ARCHIVE_LIMITS__ = {
    MaxInputBytes: 4 * 1024 * 1024,
    MaxEntries: 256,
    MaxEntryUncompressedBytes: 64 * 1024,
    MaxTotalUncompressedBytes: 4 * 1024 * 1024,
    MaxCompressionRatio: 1000,
  };
  globalThis.location = { origin: 'https://tessa.example.test', href: 'https://tessa.example.test/matrix' };
  globalThis.alert = () => {};
  globalThis.confirm = () => true;
  globalThis.URL.createObjectURL = () => 'blob:test';
  globalThis.URL.revokeObjectURL = () => {};
  globalThis.document = { body: { innerText: '' }, querySelector: () => null, querySelectorAll: () => [] };
  vm.runInThisContext(source, { filename: target });
  const E = globalThis.__TESSA_MATRIX_SYNC_EXPORTS__;
  assert.ok(E?.createRoundtripXlsxBytes && E?.readXlsxArrayBuffer && E?.refreshWorkbookDictionaries && E?.pickerColumns,
    'regression requires production XLSX and picker exports');

  const structure = { templateId: 'tpl-final-four', conditions: [], functions: [{ id: 'sign', name: 'Подписание' }] };
  const snapshot = { matrixId: 'matrix-final-four', templateId: 'tpl-final-four', rows: [] };
  const catalogId = 'roles:final-four';
  const makeCatalog = count => ({
    catalogs: {
      [catalogId]: {
        id: catalogId,
        label: 'Большой справочник',
        sourceView: 'MtxRoles',
        entries: Array.from({ length: count }, (_, index) => ({
          id: `role-${String(index).padStart(5, '0')}`,
          roleTypeId: String(index % 4),
          display: `Сотрудник ${index}`,
          selector: `Сотрудник ${index} — Должность ${index}`,
          source: 'MtxRoles',
          details: `RoleFullName: Сотрудник ${index} | RolePositionName: Должность ${index}`,
        })),
      },
    },
    columnCatalogIds: { 'function:sign': catalogId },
    stats: { errors: [] },
  });

  const smallCatalog = makeCatalog(3);
  const picker = E.pickerColumns({
    schemaTokens: ['function:sign'],
    headers: ['Подписание'],
    dictionaryCatalog: smallCatalog,
  });
  assert.equal(picker.length, 1, 'production picker contract must expose the live dictionary column');
  assert.equal(picker[0].label, 'Подписание', 'picker label must come from the matching workbook header');
  assert.equal(picker[0].catalog?.id, catalogId, 'picker must retain the mapped live catalog');

  const largeCatalog = makeCatalog(900);
  const sourceBytes = await E.createRoundtripXlsxBytes(structure, snapshot, { TemplateName: 'Final four refresh' }, smallCatalog);
  const sourceBook = await E.readXlsxArrayBuffer(
    sourceBytes.buffer.slice(sourceBytes.byteOffset, sourceBytes.byteOffset + sourceBytes.byteLength),
    'final-four-source.xlsx',
  );
  const refreshedBytes = await E.refreshWorkbookDictionaries(sourceBook, structure, largeCatalog);
  assert.ok(refreshedBytes instanceof Uint8Array && refreshedBytes.length > 0,
    'refresh with an oversized generated dictionary service sheet must succeed');
  const lean = await E.readXlsxArrayBuffer(
    refreshedBytes.buffer.slice(refreshedBytes.byteOffset, refreshedBytes.byteOffset + refreshedBytes.byteLength),
    'final-four-refreshed.xlsx',
    { skipSheetNames: ['Словари'], dictionaryCatalog: largeCatalog, retainArchive: false, selectiveInflate: true },
  );
  assert.equal(lean.rows.length, 0);
  assert.equal(lean.parsedSheets.has('Словари'), false);

  console.log('Live UAT final-four regressions: complete picker source, direct dictionary refresh and Boolean semantics: OK');
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
