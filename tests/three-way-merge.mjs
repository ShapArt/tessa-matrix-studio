import fs from 'node:fs';import vm from 'node:vm';import assert from 'node:assert/strict';
globalThis.window=globalThis;globalThis.__TESSA_MATRIX_SYNC_TEST_MODE__=true;
vm.runInThisContext(fs.readFileSync(new URL('../tessa-matrix-studio.user.js',import.meta.url),'utf8'));
const E=window.__TESSA_MATRIX_SYNC_EXPORTS__,O=E.constants.OPERAND;
const structure={templateId:'t',conditions:[{criterionRowId:'a',criterionName:'Первое',operandTypeId:O.String},{criterionRowId:'b',criterionName:'Второе',operandTypeId:O.String}],functions:[{id:"f",name:"Исполнитель"}]};
const row=(id,a,b)=>{const flat={'criterion:a':[a],'criterion:b':[b],'function:f':['Тестер']};return {index:0,rowCardId:id,versionId:'v-'+id,flat,fingerprint:E.fingerprintFlat(flat),values:{a:[{kind:'String',display:a}],b:[{kind:'String',display:b}]},roles:{f:[{id:"person",display:"Тестер",roleTypeId:1}]}}};
const snapshot={matrixId:'m',rows:[row('r','А','Б'),row('s','С','Д')]};
const buf=x=>x.buffer.slice(x.byteOffset,x.byteOffset+x.byteLength);
const book=await E.readXlsxArrayBuffer(buf(await E.createRoundtripXlsxBytes(structure,snapshot,{TemplateID:'t'})));
const local={...book,rows:book.rows.map(r=>({...r,values:[...r.values]}))};
local.rows[0].values[0]='Моё';
const fresh={...snapshot,rows:[row('r','А','Чужое'),snapshot.rows[1],row('new','Новая','Строка')]};
const result=E.prepareThreeWayMerge(local,structure,fresh);
assert.equal(result.unresolved.length,0);
const merged=E.mergeWorkbookIntoCurrentSnapshot(result.workbook,structure,fresh);
assert.deepEqual(merged.snapshot.rows[0].flat,{'criterion:a':['Моё'],'criterion:b':['Чужое'],'function:f':['Тестер']});
assert.equal(merged.snapshot.rows.length,3);
const rebook=await E.readXlsxArrayBuffer(buf(await E.createRoundtripXlsxBytes(structure,merged.snapshot,{TemplateID:'t'},null,{baselineRows:fresh.rows})));
assert.equal(E.buildPlan(rebook,structure,fresh).counts.update,1);
const collision={...fresh,rows:[row('r','Их первое','Чужое'),...fresh.rows.slice(1)]};
const pending=E.prepareThreeWayMerge(local,structure,collision);
assert.equal(pending.unresolved.length,1);
assert.equal(pending.unresolved[0].mine,'Моё');
const choose=E.prepareThreeWayMerge(local,structure,collision,{[pending.unresolved[0].id]:'server'});
assert.equal(choose.unresolved.length,0);
assert.equal(E.mergeWorkbookIntoCurrentSnapshot(choose.workbook,structure,collision).snapshot.rows[0].flat['criterion:a'][0],'Их первое');
const deleted={...book,rows:[book.rows[1]]};
const del=E.prepareThreeWayMerge(deleted,structure,fresh);
assert.equal(del.unresolved[0].kind,'local-delete');
const kept=E.prepareThreeWayMerge(deleted,structure,fresh,{[del.unresolved[0].id]:'server'});
assert.equal(E.mergeWorkbookIntoCurrentSnapshot(kept.workbook,structure,fresh).snapshot.rows.length,3);
const remoteDeleted={...snapshot,rows:[snapshot.rows[1]]};
assert.equal(E.prepareThreeWayMerge(local,structure,remoteDeleted).unresolved[0].kind,'remote-delete');
console.log('Three-way merge: unrelated edits, conflicts, baseline and deletion conflicts OK');
const chooseNew=E.prepareThreeWayMerge(local,structure,remoteDeleted,{[E.prepareThreeWayMerge(local,structure,remoteDeleted).unresolved[0].id]:'mine'});
assert.equal(E.mergeWorkbookIntoCurrentSnapshot(chooseNew.workbook,structure,remoteDeleted).snapshot.rows.length,2);
// A reference renamed or added in TESSA must stay resolvable in the older workbook.
const refs={templateId:'t',conditions:[{criterionRowId:'a',criterionName:'Ссылка',operandTypeId:O.ReferenceGuid}],functions:[{id:'f',name:'Роль'}]};
const refRow=(id,label)=>({rowCardId:'r',versionId:'v-r',index:0,flat:{'criterion:a':[label],'function:f':['Тестер']},values:{a:[{id,display:label}]},roles:{f:[{id:'person',display:'Тестер',roleTypeId:1}]}});
const before=refRow('old','Раньше');before.fingerprint=E.fingerprintFlat(before.flat);
const after=refRow('new','Новое');after.fingerprint=E.fingerprintFlat(after.flat);
const oldSnap={matrixId:'m',rows:[before]},newSnap={matrixId:'m',rows:[after]};
const oldCatalog=E.mergeSnapshotIntoDictionaryCatalog(null,refs,oldSnap);
const oldBook=await E.readXlsxArrayBuffer(buf(await E.createRoundtripXlsxBytes(refs,oldSnap,{TemplateID:'t'},oldCatalog)));
const referenceMerge=E.prepareThreeWayMerge(oldBook,refs,newSnap);
assert.equal(referenceMerge.unresolved.length,0);
assert.equal(E.mergeWorkbookIntoCurrentSnapshot(referenceMerge.workbook,refs,newSnap).snapshot.rows[0].values.a[0].id,'new');
